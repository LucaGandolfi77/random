export function getFusionRecipe(cardId1, cardId2) {
  const id1 = typeof cardId1 === 'object' ? cardId1.id : cardId1;
  const id2 = typeof cardId2 === 'object' ? cardId2.id : cardId2;

  return FUSION_RECIPES.find(recipe => {
    return (recipe.card1 === id1 && recipe.card2 === id2) ||
           (recipe.card1 === id2 && recipe.card2 === id1);
  }) || null;
}

export function canFuse(card1, card2) {
  return getFusionRecipe(card1, card2) !== null;
}
