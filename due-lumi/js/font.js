  const canvases = {};
  function glyphCanvas(ch){
    const rows = GLYPH[ch];
    if(!rows) return null;
    let c = document.createElement('canvas');
    c.width = W; c.height = H;
    const x = c.getContext('2d');
    for(let r=0;r<H;r++){
      const row = rows[r];
      for(let cc=0;cc<W;cc++){
        if(row[cc] === '#'){ x.fillStyle = '#fff'; x.fillRect(cc,r,1,1); }
      }
    }
    return c;
  }
  function gc(ch){
    if(canvases[ch]) return canvases[ch];
    return canvases[ch] = glyphCanvas(ch);
  }

  function measure(str){ return str.length * W; }

  const tinted = {};
  function tintGlyph(ch, col){
    const ck = ch + ':' + col;
    if(tinted[ck]) return tinted[ck];
    const base = gc(ch);
    if(!base) return null;
    const tmp = document.createElement('canvas');
    tmp.width = W; tmp.height = H;
    const tx = tmp.getContext('2d');
    tx.drawImage(base, 0, 0);
    tx.globalCompositeOperation = 'source-in';
    tx.fillStyle = col;
    tx.fillRect(0, 0, W, H);
    return tinted[ck] = tmp;
  }

  /* draw text with optional outline. colors are palette keys. */
  function draw(ctx, str, x, y, color, opts){
    opts = opts || {};
    const col = hex(color || 'ink');
    const out = opts.outline ? hex(opts.outline) : null;
    const sx = Math.round(x), sy = Math.round(y);
    ctx.save();
    if(opts.scale && opts.scale !== 1){
      ctx.translate(sx, sy); ctx.scale(opts.scale, opts.scale); ctx.translate(-sx, -sy);
    }
    for(let i=0;i<str.length;i++){
      const ch = str[i];
      if(ch === '\n') continue;
      const g = gc(ch);
      if(!g) continue;
      const px = sx + i*W, py = sy;
      if(out){
        const og = tintGlyph(ch, out);
        if(og){
          ctx.globalAlpha = opts.outAlpha==null ? 0.9 : opts.outAlpha;
          ctx.drawImage(og, px+1, py); ctx.drawImage(og, px-1, py);
          ctx.drawImage(og, px, py+1); ctx.drawImage(og, px, py-1);
          ctx.globalAlpha = 1;
        }
      }
      const tg = tintGlyph(ch, col);
      if(tg) ctx.drawImage(tg, px, py);
    }
    ctx.restore();
  }

  return { W, H, measure, draw, glyphs: GLYPH };
