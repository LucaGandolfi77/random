export const MOON_NAMES = { it: moonIt, en: moonEn };

export function t(lang, key, vars) {
  const table = STR[lang] || STR.it;
  let s = table[key] ?? STR.it[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      s = s.replaceAll(`{${k}}`, String(v));
    });
  }
  return s;
}
